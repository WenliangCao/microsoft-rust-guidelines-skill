#!/usr/bin/env python3
"""Vendor a pinned Microsoft Rust Guidelines snapshot; --check works offline."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = "https://github.com/microsoft/rust-guidelines"
WEBSITE = "https://microsoft.github.io/rust-guidelines/"
MANIFEST = "references/snapshot.json"
INDEX = "references/index.md"
UPSTREAM = "references/upstream/"


def sha256(content):
    return hashlib.sha256(content).hexdigest()


def heading(path, level):
    text = path.read_text(encoding="utf-8-sig")
    match = re.search(rf"^{'#' * level} (.+)$", text, re.MULTILINE)
    if not match:
        raise ValueError(f"Missing heading in {path}")
    return match.group(1)


def build_snapshot(source, revision):
    """Build generated files in memory, retaining original source bytes."""
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("Expected a full upstream commit SHA")
    guidelines = source / "src/guidelines"
    rules = sorted(guidelines.rglob("M-*.md"))
    if not rules:
        raise ValueError("No upstream rules found")

    files = {}
    topics = {}
    seen = set()
    for rule in rules:
        title = heading(rule, 2)
        match = re.fullmatch(r"(.+) \((M-[A-Z0-9-]+)\) \{ #\2 \}", title)
        if not match or match.group(2) != rule.stem or rule.stem in seen:
            raise ValueError(f"Invalid or duplicate rule ID: {rule}")
        seen.add(rule.stem)
        relative = rule.relative_to(guidelines).as_posix()
        files[UPSTREAM + relative] = rule.read_bytes()
        topics.setdefault(rule.parent, []).append((relative, match.group(1), rule.stem))

        # Keep illustrations used by the original rule, with their relative paths.
        text = rule.read_text(encoding="utf-8-sig")
        for image in re.findall(r"!\[[^\]]*\]\(([^)]+)\)", text):
            if image.startswith(("https://", "http://")):
                continue
            asset = (rule.parent / image).resolve()
            if not asset.is_relative_to(guidelines.resolve()):
                raise ValueError(f"Image outside guidelines: {image}")
            files[UPSTREAM + asset.relative_to(guidelines.resolve()).as_posix()] = asset.read_bytes()

    files[UPSTREAM + "README.md"] = (guidelines / "README.md").read_bytes()
    files[UPSTREAM + "LICENSE.md"] = (source / "LICENSE.md").read_bytes()
    index = [
        "<!-- Generated by scripts/sync_guidelines.py. Do not edit by hand. -->",
        "<!-- Upstream titles: Copyright (c) Microsoft Corporation. MIT license. -->",
        "",
        "# Rule index",
        "",
        f"Source: [{revision[:12]}]({REPOSITORY}/tree/{revision}/src/guidelines).",
        f"Includes all {len(rules)} M-* rules across {len(topics)} topics at this commit.",
        "Read only the rule files relevant to the task, including their exceptions.",
        "",
        "[Upstream scope and applicability](upstream/README.md) · "
        "[Snapshot metadata](snapshot.json) · [Upstream license](upstream/LICENSE.md)",
        "",
    ]
    for folder, entries in sorted(topics.items()):
        index.extend([f"## {heading(folder / 'README.md', 1)}", ""])
        for path, title, rule_id in entries:
            index.append(f"- [{rule_id} — {title}](upstream/{path})")
        index.append("")
    files[INDEX] = "\n".join(index).encode("utf-8")
    manifest = {
        "repository": REPOSITORY,
        "website": WEBSITE,
        "revision": revision,
        "rule_count": len(rules),
        "topic_count": len(topics),
        "files": {path: sha256(data) for path, data in sorted(files.items())},
    }
    files[MANIFEST] = (json.dumps(manifest, indent=2) + "\n").encode("utf-8")
    return files


def write_snapshot(root, files):
    """Replace only the generated reference files owned by this script."""
    for path in (root / UPSTREAM).rglob("*"):
        if path.is_file() and path.relative_to(root).as_posix() not in files:
            path.unlink()
    for name, content in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)


def check_snapshot(root):
    manifest = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
    expected = manifest["files"]
    actual = {path.relative_to(root).as_posix() for path in (root / UPSTREAM).rglob("*") if path.is_file()}
    actual.add(INDEX)
    if set(expected) != actual:
        raise ValueError(f"Snapshot file set changed: {sorted(set(expected) ^ actual)}")
    for name, digest in expected.items():
        if sha256((root / name).read_bytes()) != digest:
            raise ValueError(f"Snapshot content changed: {name}")
    rules = [name for name in expected if re.search(r"/M-[^/]+\.md$", name)]
    topics = {str(Path(name).parent) for name in rules}
    if len(rules) != manifest["rule_count"] or len(topics) != manifest["topic_count"]:
        raise ValueError("Snapshot rule or topic count changed")
    if not re.fullmatch(r"[0-9a-f]{40}", manifest["revision"]):
        raise ValueError("Invalid snapshot revision")
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Verify the recorded snapshot offline")
    mode.add_argument("--ref", help="Upstream commit, tag, or branch to fetch (e.g. main)")
    args = parser.parse_args()
    if args.check:
        manifest = check_snapshot(ROOT)
        print(f"Verified {manifest['rule_count']} rules at {manifest['revision'][:12]}")
        return

    ref = args.ref
    if ref is None:
        ref = json.loads((ROOT / MANIFEST).read_text(encoding="utf-8"))["revision"]
    if not ref or ref.startswith("-"):
        parser.error("--ref must be a commit, tag, or branch")
    with tempfile.TemporaryDirectory(prefix="rust-guidelines-sync-") as directory:
        source = Path(directory)
        subprocess.run(["git", "init", "--quiet", str(source)], check=True)
        subprocess.run(["git", "-C", str(source), "fetch", "--quiet", "--depth=1", REPOSITORY + ".git", ref], check=True)
        subprocess.run(["git", "-C", str(source), "checkout", "--quiet", "--detach", "FETCH_HEAD"], check=True)
        revision = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
        files = build_snapshot(source, revision)
    write_snapshot(ROOT, files)
    manifest = check_snapshot(ROOT)
    print(f"Synced {manifest['rule_count']} rules at {revision}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        raise SystemExit(f"Error: {error}") from error
